package ru.protonmod.next.data.repository

import ru.protonmod.next.data.network.WarpEndpoints
import ru.protonmod.next.vpn.ImportedWireGuard

/** Pure storage/identity rules, shared by encrypted persistence and chain resolution. */
object CustomConfigRules {
    const val WARP_ID = "warp"
    fun find(configs: List<CustomConfig>, id: String) = configs.find { it.id == id || id in it.previousIds }
    private fun legacyWarp(config: CustomConfig): Boolean = runCatching {
        if (config.name != "WARP" || !config.link.startsWith(ImportedWireGuard.SCHEME)) return false
        val text = ImportedWireGuard.decode(config.link)
        // Conservative signature of configs generated by the previous app version.
        val endpoint = Regex("(?m)^Endpoint = (.+)$").find(text)?.groupValues?.get(1)?.substringBeforeLast(':')
        endpoint in WarpEndpoints.allIps || endpoint == "engage.cloudflareclient.com"
    }.getOrDefault(false) && runCatching {
        val text = ImportedWireGuard.decode(config.link)
        listOf("Address = 172.16.0.2/32", "DNS = 1.1.1.1", "MTU = 1280", "PersistentKeepalive = 25").all(text::contains)
    }.getOrDefault(false)

    fun migrate(configs: List<CustomConfig>): List<CustomConfig> {
        val warps = configs.filter { it.isWarp || legacyWarp(it) }
        if (warps.isEmpty()) return configs
        val latest = warps.last()
        val aliases = warps.flatMap { it.previousIds + it.id }.filterNot { it == WARP_ID }.distinct()
        return configs.filterNot { it in warps } + latest.copy(id = WARP_ID, kind = "warp", name = "WARP", previousIds = aliases)
    }
    fun replaceWarp(configs: List<CustomConfig>, link: String): List<CustomConfig> {
        val current = migrate(configs)
        val previous = current.firstOrNull { it.isWarp }
        require(current.size < 100 || previous != null)
        return current.filterNot { it.isWarp } + CustomConfig(id = WARP_ID, name = "WARP", link = link,
            kind = "warp", previousIds = previous?.previousIds.orEmpty())
    }
    fun resolveChain(configs: List<CustomConfig>, raw: String, warpEnabled: Boolean): String =
        raw.lineSequence().map(String::trim).filter(String::isNotEmpty).joinToString("\n") { link ->
            if (!link.startsWith("custom://")) link else {
                val config = requireNotNull(find(configs, link.removePrefix("custom://")))
                require(!config.isWarp || warpEnabled) { "WARP is disabled" }
                config.link
            }
        }
    fun appendHop(raw: String, config: CustomConfig): String {
        val links = raw.lineSequence().map(String::trim).filter(String::isNotEmpty).toList()
        require(links.size < 4 && links.none { it == "custom://${config.id}" || it.removePrefix("custom://") in config.previousIds })
        return (links + "custom://${config.id}").joinToString("\n")
    }
}
